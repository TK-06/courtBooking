test('booking detail gets its id from the route and renders live history in order, deduplicated and filtered', async () => {
  const event = { id:1, bookingId:'b1', text:'Booked Court I', kind:'booking.created', source:'Make.com', createdAt:new Date('2026-11-10T05:00:00Z') }
  fake.events.mockResolvedValue([event])
  const w = render(BookingDetail)
  await flushPromises()
  expect(fake.events).toHaveBeenCalledWith({ bookingId:'b1' })
  expect(w.text()).toContain('Napat Srisuk')
  expect(w.text()).toContain('You can cancel until Thu 12 Nov, 16:00.')
  fake.insert({ ...event, id:2, text:'Cancelled Court I', kind:'booking.cancelled', createdAt:new Date('2026-11-10T06:00:00Z') })
  fake.insert(event)
  fake.insert({ ...event, id:3, bookingId:'someone-else', text:'Private event' })
  await flushPromises()
  expect(w.findAll('.tl-text').map(e => e.text())).toEqual(['Booked Court I','Cancelled Court I'])
  w.unmount(); wrappers.pop()
  expect(fake.unsubscribe).toHaveBeenCalledTimes(1)
})
