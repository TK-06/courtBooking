import { afterEach, beforeEach, expect, test, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { reactive, ref } from 'vue'
import Home from '../../src/views/Home.vue'
import MyBookings from '../../src/views/MyBookings.vue'
import BookingDetail from '../../src/views/BookingDetail.vue'
import TicketCard from '../../src/components/TicketCard.vue'

const fake = vi.hoisted(() => ({ mine:vi.fn(), bookings:vi.fn(), courts:vi.fn(), closed:vi.fn(), events:vi.fn(), profiles:vi.fn(), cancel:vi.fn(), subscribe:vi.fn(), unsubscribe:vi.fn(), push:vi.fn(), show:vi.fn(), route:null, auth:null, insert:null }))
vi.mock('../../src/lib/api.js', () => ({ fetchMyBookings:fake.mine, fetchBookings:fake.bookings, fetchCourts:fake.courts, fetchClosedDays:fake.closed, fetchEvents:fake.events, fetchProfiles:fake.profiles, cancelBooking:fake.cancel, subscribeEvents:fake.subscribe }))
vi.mock('../../src/composables/useAuth.js', () => ({ useAuth:() => fake.auth }))
vi.mock('../../src/composables/useToast.js', () => ({ useToast:() => ({ show:fake.show }) }))
vi.mock('vue-router', () => ({ useRoute:() => fake.route, useRouter:() => ({ push:fake.push }) }))
const booking = { id:'b1', userId:'u1', courtId:1, date:'2026-11-12', start:18, end:20, status:'confirmed', purpose:null, code:'ITC-1112-0001', createdAt:new Date('2026-11-10T05:00:00Z') }
const courts = [{ id:1, name:'Court I', status:'open', note:'' }, { id:2, name:'Court II', status:'closed', note:'Closed for resurfacing. Reopening date to follow.' }]
const wrappers = []
function render(component, options) { const w = mount(component, options); wrappers.push(w); return w }
beforeEach(() => {
  vi.clearAllMocks()
  vi.useFakeTimers({ toFake:['Date'] })
  vi.setSystemTime(new Date('2026-11-10T06:20:00Z'))
  fake.auth = { profile:ref({ id:'u1', fullName:'Napat Srisuk', studentId:'6638012321' }), session:ref({ user:{ id:'u1' } }), mode:ref('student'), isAdmin:ref(false) }
  fake.route = reactive({ params:{ id:'b1' }, query:{}, fullPath:'/booking/b1' })
  fake.mine.mockResolvedValue([booking])
  fake.bookings.mockResolvedValue([booking])
  fake.courts.mockResolvedValue(courts)
  fake.closed.mockResolvedValue({})
  fake.events.mockResolvedValue([])
  fake.profiles.mockResolvedValue([{ id:'u1', fullName:'Napat Srisuk', studentId:'6638012321' }])
  fake.cancel.mockResolvedValue({ ...booking, status:'cancelled', cancelReason:'Weather', cancelledBy:'member' })
  fake.subscribe.mockImplementation(callback => { fake.insert = callback; return fake.unsubscribe })
})
afterEach(() => { wrappers.splice(0).forEach(w => w.unmount()); vi.useRealTimers() })
test('ticket options emit cancel and open without opening the card accidentally', async () => {
  const w = render(TicketCard, { props:{ booking, menu:true, label:'Next booking' } })
  await w.get('[aria-label="Booking options"]').trigger('click')
  await w.findAll('[role="menuitem"]')[1].trigger('click')
  expect(w.emitted('cancel')).toEqual([['b1']])
  expect(w.emitted('open')).toBeUndefined()
  await w.trigger('keydown', { key:'Enter' })
  expect(w.emitted('open')).toEqual([['b1']])
})
test('Home uses real Bangkok time, counts free hours and navigates court query', async () => {
  const w = render(Home)
  await flushPromises()
  expect(w.text()).toContain('Good afternoon, Napat.')
  expect(w.text()).toContain('8 hours open today')
  expect(fake.bookings).toHaveBeenCalledWith({ from:'2026-11-10', to:'2026-11-10' })
  await w.findAll('.court-btn')[0].trigger('click')
  expect(fake.push).toHaveBeenCalledWith({ name:'book', query:{ court:1 } })
  await w.findAll('.court-btn')[1].trigger('click')
  expect(fake.show).toHaveBeenCalledWith('Court II: ' + courts[1].note)
})
